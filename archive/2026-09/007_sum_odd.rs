// 题目要求：
// 实现一个函数，接收一个 i32 整数 n，返回 1 到 n 之间所有奇数的和。
// 如果 n <= 0，返回 0。
//
// 示例：
// 输入：10 → 输出：25（1 + 3 + 5 + 7 + 9 = 25）
// 输入：7  → 输出：16（1 + 3 + 5 + 7 = 16）
// 输入：0  → 输出：0（n <= 0 返回 0）
//
// 提示：
// - 使用循环 `for i in 1..=n` 遍历
// - 判断奇数可以用 `i % 2 == 1`，或者用 `i % 2 != 0`
// - 注意负数情况，先处理 n <= 0 返回 0

pub fn exercise_fn(n: i32) -> i32 {
    if n <= 0 {return 0};
    let mut sum = 0;
    for i in 1 ..= n {
        if i % 2 != 0 {
            sum += i
        }
    }
    sum
}
