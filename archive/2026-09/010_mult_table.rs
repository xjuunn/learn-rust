// 题目要求：
// 实现一个函数，接收一个整数 n（1 <= n <= 10），
// 输出 n 的乘法表（从 1 乘到 n）的和。
//
// 即：计算 1*1 + 1*2 + ... + 1*n
//         + 2*1 + 2*2 + ... + 2*n
//         + ... 
//         + n*1 + n*2 + ... + n*n
// 的总和。
//
// 也就是 (1+2+...+n) * (1+2+...+n)，即连续整数平方和公式的应用。
//
// 示例：
// 输入：2 → 输出：9（1*1+1*2+2*1+2*2 = 1+2+2+4 = 9）
// 输入：3 → 输出：36（1+2+3=6，6*6=36）
//
// 提示：
// - 外层循环 i 从 1 到 n，内层循环 j 从 1 到 n
// - 累加 i * j
// - 题目考验嵌套循环和累加

pub fn exercise_fn(n: i32) -> i32 {
    let mut sum = 0;
    for i in 1..=n {
        for j in 1..=n {
            sum += i * j;
        }
    }
    sum
}
