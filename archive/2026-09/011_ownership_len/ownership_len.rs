// 题目要求：
// 实现一个函数，接收一个字符串 String，返回它的长度（字节数）。
//
// 这道题的目的是理解所有权：
// 函数接收 String 的所有权后，String 在函数结束时会被释放。
//
// 请尝试：
// 1. 在函数中调用 s.len() 获取长度
// 2. 返回长度
// 3. 思考：参数 s 的所有权发生了什么？
//
// 示例：
// 输入："hello" → 输出：5
// 输入："世界" → 输出：6（"世界" 每个汉字占 3 字节，共 6 字节）
//
// 提示：
// - String 的 .len() 返回字节数（不是字符数）
// - 接收 String 意味着所有权被移动到函数内

pub fn exercise_fn(s: String) -> usize {
    s.len()
}
