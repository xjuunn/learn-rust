// 题目要求：
// 实现一个函数，接收一个字符串切片 &str 表示词语，计算其"评分"。
//
// 评分规则：
// 1. 每个字母的评分 = 字母在字母表中的位置（a=1, b=2, ..., z=26），
//    不区分大小写（A 和 a 都算 1）
// 2. 词语总分 = 所有字母评分之和
// 3. 空格不计分
//
// 示例：
// 输入："abc" → 输出：6（1 + 2 + 3 = 6）
// 输入："CAT" → 输出：24（3 + 1 + 20 = 24）
// 输入："a b" → 输出：3（a=1, b=2，空格不计分）
//
// 提示：
// - 使用 .to_ascii_lowercase() 转小写，或用 .to_lowercase()
// - 遍历字符用 for c in s.chars()
// - 字符转数字：c as u32 可得到 ASCII 码，'a' 的 ASCII 是 97
//   （小写字母的评分 = ASCII码 - 96）

pub fn exercise_fn(s: &str) -> u32 {
    let mut star = 0;
    for c in s.chars() {
        let c = c.to_ascii_lowercase() as u32;
        if c >= 'a' as u32 && c <= 'z' as u32 {
            star += c - 'a' as u32 + 1;
        }
    }
    star
}
