// 题目要求：
// 实现一个函数，接收两个字符串切片 &str（first 和 second），
// 返回两者中较长（按字符数，即 .len()）的那一个（&str 引用）。
//
// 这道题的目的是理解"生命周期"：
// 函数要返回一个引用，必须标注生命周期参数 'a，
// 告诉编译器返回的引用与输入参数的生命周期关联。
//
// 示例：
// 输入：("abc", "de") → 输出："abc"
// 输入：("a", "bcd") → 输出："bcd"
// 输入：("xy", "ab") → 输出："xy"（长度相同返回 first）
//
// 提示：
// - 使用 .len() 比较长度（都按字节，ASCII 测试即可）
// - 函数签名需要生命周期标注：fn exercise_fn<'a>(first: &'a str, second: &'a str) -> &'a str
// - 注意提示栏已给签名，请使用带生命周期的签名

pub fn exercise_fn<'a>(first: &'a str, second: &'a str) -> &'a str {
    if first.len() >= second.len() {
        first
    } else {
        second
    }
}
