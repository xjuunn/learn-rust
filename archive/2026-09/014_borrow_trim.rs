// 题目要求：
// 实现一个函数，接收一个字符串的不可变引用 &str，
// 返回它去掉首尾空白后的字符串（String）。
//
// 这道题的目的是理解"借用"：
// 接收 &str 只是借用，不会取得所有权，函数结束后原字符串依然可用。
//
// 示例：
// 输入："  hello  " → 输出："hello"
// 输入："  世界  " → 输出："世界"
// 输入：“   ”      → 输出：""
//
// 提示：
// - 使用 .trim() 方法去掉首尾空白
// - .trim() 返回 &str，需要用 .to_string() 或 .to_owned() 转为 String

pub fn exercise_fn(s: &str) -> String {
    s.to_string().trim().to_string()
}
