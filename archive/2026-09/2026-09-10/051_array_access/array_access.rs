/// 安全地访问数组中的元素。
/// 如果索引越界，panic! 并给出包含数组长度和请求索引的错误信息。
///
/// 例子：
///   safe_access(&[10, 20, 30], 1) -> 20
///   safe_access(&[10, 20, 30], 5) -> panic: "索引 5 越界，数组长度为 3"
///
/// 注意：错误信息格式必须是 "索引 {index} 越界，数组长度为 {len}"
pub fn safe_access(arr: &[i32], index: usize) -> i32 {
    // 填空 1：检查索引是否越界，如果越界则 panic! 并给出错误信息
    // 如果没越界，返回 arr[index]
    if arr.len() <= index {
        panic!("索引 {} 越界，数组长度为 {}", index, arr.len());
    }
    arr[index]
}

/// 入口函数：演示数组安全访问
/// 接收数组和多个索引，返回成功访问的结果列表
///
/// 例子：
///   exercise_fn(&[10, 20, 30], &[0, 2]) -> vec![10, 30]
///   exercise_fn(&[10, 20, 30], &[0, 5]) -> panic on index 5
pub fn exercise_fn(arr: &[i32], indices: &[usize]) -> Vec<i32> {
    // 填空 2：遍历 indices，对每个索引调用 safe_access
    // 收集结果到 Vec 并返回
    indices
        .iter()
        .map(|index| safe_access(arr, *index))
        .collect()
}
