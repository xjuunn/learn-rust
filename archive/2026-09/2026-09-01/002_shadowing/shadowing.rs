// 题目要求：
// 1. 使用 let 绑定一个变量 x，值为 "hello"
// 2. 使用 let 遮蔽 x，将其转换为字符串长度（使用 .len()）
// 3. 再次使用 let 遮蔽 x，将其转换为 f64 类型
// 4. 返回最终的 x 值（f64 类型）
//
// 示例：
// 输入：无
// 输出：5.0（"hello" 的长度是 5，转换为 f64 后是 5.0）
//
// 提示：遮蔽允许我们改变变量的类型，而不需要使用 mut

pub fn exercise_fn() -> f64 {
    let x = "hello";
    let x = x.len();
    let x = x as f64;
    x
}
