// 题目要求：
// 实现一个函数，接收三个参数判断三角形类型：
//   a: i32（第一条边）
//   b: i32（第二条边）
//   c: i32（第三条边）
//
// 返回一个 &'static str 表示三角形类型：
// - "等边"    ：三条边都相等
// - "等腰"    ：有两条边相等（但不是等边）
// - "不等边"  ：三条边都不相等
//
// 注意：
// - 若任一边 <= 0，返回 "无效"
// - 若不能构成三角形（任两边之和 <= 第三边），返回 "无效"
//
// 示例：
// 输入：(3, 3, 3) → 输出："等边"
// 输入：(3, 3, 5) → 输出："等腰"
// 输入：(3, 4, 5) → 输出："不等边"
// 输入：(1, 1, 2) → 输出："无效"（1+1=2 不构成三角形）
// 输入：(0, 3, 3) → 输出："无效"（有边为 0）
//
// 提示：
// - 先检查无效情况（边 <=0 或 构不成三角形）
// - 再用相等比较判断等边/等腰/不等边

pub fn exercise_fn(a: i32, b: i32, c: i32) -> &'static str {
    if a<=0 || b<=0 || c<=0 {
        return "无效";
    }
    if a + b <=c {
        return "无效";
    }
    if a == b && b == c {
        return "等边";
    }
    if a == b || b == c || a == c {
        return "等腰"
    }
    "不等边"
}
