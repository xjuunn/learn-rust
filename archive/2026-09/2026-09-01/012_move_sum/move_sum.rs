// 题目要求：
// 实现一个函数，接收一个 Vec<i32>，返回其中所有元素的和。
//
// 这道题的目的是理解"移动语义"：
// 把 Vec 传给函数时，Vec 的所有权被转移（移动）到函数参数中，
// 原变量在函数调用后就不能再使用了。
//
// 注意：由于参数是 Vec<i32>（不是 &Vec<i32>），函数会"消耗"这个 Vec，
// 调用后原 Vec 的所有权不再存在——这正是移动语义的体现。
//
// 示例：
// 输入：vec![1, 2, 3] → 输出：6
// 输入：vec![10, 20] → 输出：30
//
// 提示：
// - 直接遍历 Vec 的所有元素累加
// - 思考：为什么调用后原 Vec 不能再被使用？

pub fn exercise_fn(v: Vec<i32>) -> i32 {
    let mut sum = 0;
    for i in v {
        sum += i;
    }
    sum
}
