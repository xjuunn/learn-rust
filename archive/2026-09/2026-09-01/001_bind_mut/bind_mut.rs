// 题目要求：
// 1. 使用 let 绑定一个不可变变量 x，值为 5
// 2. 使用 let mut 绑定一个可变变量 y，初始值为 10
// 3. 将 y 的值修改为 x + y 的结果
// 4. 返回 y 的值
//
// 示例：
// 输入：无
// 输出：15（因为 x=5, y=10, 最后 y = 5 + 10 = 15）
//
// 提示：思考 let 和 let mut 的区别，只有 mut 变量才能被重新赋值

pub fn exercise_fn() -> i32 {
    let x = 5;
    let mut y = 10;
    y = x + y;
    y
}
