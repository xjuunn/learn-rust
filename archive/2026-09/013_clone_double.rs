// 题目要求：
// 实现一个函数，接收一个 Vec<i32>，返回一个新 Vec，
// 其中每个元素都乘以 2。
//
// 这道题的目的是理解"克隆"：
// 需要保留原始 Vec 的同时，创建一个新的 Vec。
// 使用 .clone() 复制原始 Vec 的所有权，这样原始 Vec 不被移动。
//
// 示例：
// 输入：vec![1, 2, 3] → 输出：vec![2, 4, 6]
// 输入：vec![5] → 输出：vec![10]
//
// 提示：
// - 传入的参数是 Vec<i32>（有所有权）
// - 可以先克隆一份再遍历，或者迭代时值类型 i32 本身是 Copy 的
//   （i32 是 Copy，遍历时以值取用不会移动整个 Vec）
// - 用 .iter().map(|x| x * 2).collect() 是最简洁的方式

pub fn exercise_fn(v: Vec<i32>) -> Vec<i32> {
    v.clone().iter().map(|f| f *2).collect()
}
