// 题目要求：
// 下面的代码存在一个"编译错误"：它试图在仍持有 first 元素的可变借用时，
// 又调用 v.push(...) 对 v 进行可变借用，两者重叠触发了 borrow checker 报错。
// 请找出问题并修复，使代码能通过编译并返回正确结果。
//
// 期望行为：
// 接收一个 &mut Vec<i32>：
// - 若 Vec 非空：把第一个元素翻倍，并把翻倍后的值追加到 Vec 末尾，然后返回
//   修改后的 Vec 副本
// - 若 Vec 为空：直接返回空 Vec
//
// 示例：
// 输入：&mut vec![2, 3, 4] → 输出：vec![4, 3, 4, 4]（首元素2翻倍为4，末尾追加4）
// 输入：&mut vec![5]      → 输出：vec![10, 10]（5翻倍为10，末尾追加10）
// 输入：&mut vec![]       → 输出：vec![]
//
// 提示：
// - 下面 `v.push(*first)` 中 *first 仍在使用 first 这个可变借用，而 push 又需要
//   可变借用 v，两者重叠导致编译失败
// - 修复思路：先把 *first 的值复制到一个独立的 i32 变量（副本），结束对 first
//   的借用，再执行 v.push(副本) 和 v.clone()
// - 只要满足上述期望行为并消除借用冲突即可，实现方式不限

pub fn exercise_fn(v: &mut Vec<i32>) -> Vec<i32> {
    if let Some(first) = v.first_mut() {
        let first2 = first.clone();
        *first *= 2;
        v.push(first2 * 2);
    }
    v.clone()
}
