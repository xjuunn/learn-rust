// 题目要求：
// 下面的代码中有一处被注释掉的关键行 `/* ____ */`，这是实现"把 Vec
// 中所有元素乘以 2，并返回元素个数"所必需的。请补全这一行，使代码编译通过
// 并返回正确结果。
//
// 期望行为：
// 接收一个 &mut Vec<i32>，把每个元素都乘以 2，并返回原来的元素个数。
//
// 示例：
// 输入：&mut vec![1, 2, 3] → 返回 3，且 v 变为 [2, 4, 6]
// 输入：&mut vec![]       → 返回 0
//
// 提示：
// - 返回的是"处理前的元素个数"，而处理过程中 Vec 会被修改，
//   所以需要在修改前先记下 len
// - 被注释掉的那一行，是用于"记录处理前的元素个数"，并把结果保存到
//   一个名为 original_len 的不可变变量中（注意行尾要加分号）
// - 补全后请确保：先取原长度 → 再遍历修改元素 → 最后返回原长度

pub fn exercise_fn(v: &mut Vec<i32>) -> usize {
    /* ____ */
    let original_len = v.len();
    for x in v.iter_mut() {
        *x *= 2;
    }
    original_len
}
