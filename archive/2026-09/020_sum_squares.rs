// 题目要求：
// 本题请你**从头定义一个函数**，并在入口函数 exercise_fn 中调用它。
//
// 请定义一个名为 `sum_squares` 的函数：
// - 接收一个 `&[i32]`（切片借用，不取得所有权）
// - 返回其中所有元素的平方和（i32）
// - 即对每个元素 x，累加 x * x
//
// 然后在 exercise_fn 中调用 sum_squares，返回传入切片 `data` 的平方和。
//
// 示例：
// 输入：&[1, 2, 3] → 输出：14（1² + 2² + 3² = 1 + 4 + 9 = 14）
// 输入：&[]       → 输出：0
// 输入：&[-2, 5]  → 输出：29（4 + 25 = 29）
//
// 提示：
// - sum_squares 需要接收切片 `&[i32]` 的不可变引用（借用）
// - 遍历用 `for &x in slice`（用 & 解构出值）或 `for x in slice`（x 是 &i32）
// - 累加 x * x
// - 入口函数 exercise_fn 接收 data 后，把 &data 传给 sum_squares

fn sum_squares(data: &[i32]) -> i32 {
    data.iter().map(|f| *&f.pow(2)).sum::<i32>()
}


pub fn exercise_fn(data: &[i32]) -> i32 {
    sum_squares(data)
}
