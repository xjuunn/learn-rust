// 题目要求：
// 实现一个函数，接收三个参数并返回它们的和（f64 类型）：
// 1. 整数 a（i32）
// 2. 浮点数 b（f64）
// 3. 整数 c（u32）
//
// 注意：需要将整数转换为 f64 才能与浮点数相加
//
// 示例：
// 输入：(3, 2.5, 2)
// 输出：7.5（3 + 2.5 + 2 = 7.5）
//
// 提示：使用 `as f64` 将整数转换为浮点数

pub fn exercise_fn(a: i32, b: f64, c: u32) -> f64 {
    let a = a as f64;
    let c = c as f64;
    a + b + c
}
